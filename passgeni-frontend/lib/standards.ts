// Compliance standard definitions and per-control checks.
// Pure module: no network, no DOM. The credential never leaves this process.
// Ported from the V2 ruleset (lib/compliance.js @ 2e03200) with updated citations.

export type CredentialAnalysis = {
  length: number;
  hasUpper: boolean;
  hasLower: boolean;
  hasDigit: boolean;
  hasSymbol: boolean;
  classCount: number;
  entropyBits: number;
  hasRepeatRun: boolean; // aaa / 111
  hasSequence: boolean; // abc / 321 / qwe
  dictionaryHits: string[]; // wordlist words >= 4 chars found inside the credential
  mode: "password" | "passphrase";
  wordCount?: number;
};

export type ControlResult = {
  id: string;
  label: string;
  requirement: string;
  ref: string;
  pass: boolean;
  detail: string;
};

export type StandardResult = {
  id: StandardId;
  label: string;
  shortLabel: string;
  locked: boolean;
  verdict: "pass" | "fail";
  passed: number;
  total: number;
  controls: ControlResult[];
};

type ControlDef = {
  id: string;
  label: string;
  requirement: string;
  ref: string;
  check: (a: CredentialAnalysis) => { pass: boolean; detail: string };
};

export type StandardId = "NIST-800-63B" | "SOC2" | "HIPAA" | "PCI-DSS-v4";

type StandardDef = {
  id: StandardId;
  label: string;
  shortLabel: string;
  locked: boolean; // locked = verdict computed locally, control detail gated (Pro)
  description: string;
  controls: ControlDef[];
};

const fmtBits = (b: number) => `${b.toFixed(1)} bits`;

const classDetail = (a: CredentialAnalysis) =>
  [
    a.hasUpper ? "upper" : null,
    a.hasLower ? "lower" : null,
    a.hasDigit ? "digit" : null,
    a.hasSymbol ? "symbol" : null,
  ]
    .filter(Boolean)
    .join(" + ") || "none";

