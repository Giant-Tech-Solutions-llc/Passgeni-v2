export function evaluateStandards(a: CredentialAnalysis): StandardResult[] {
  return STANDARDS.map((s) => {
    const controls = s.controls.map((c) => {
      const { pass, detail } = c.check(a);
      return { id: c.id, label: c.label, requirement: c.requirement, ref: c.ref, pass, detail };
    });
    const passed = controls.filter((c) => c.pass).length;
    return {
      id: s.id,
      label: s.label,
      shortLabel: s.shortLabel,
      locked: s.locked,
      verdict: passed === controls.length ? ("pass" as const) : ("fail" as const),
      passed,
      total: controls.length,
      controls,
    };
  });
}
